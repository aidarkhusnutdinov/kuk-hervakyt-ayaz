/* =========================================================================
   СЛОВА, КОТОРЫЕ ПАДАЮТ С НЕБА
   -------------------------------------------------------------------------
   Каждая новая строка — новая группа. Все слова внутри одной группы
   рифмуются между собой. Слова разделяются запятыми.

   Можно добавлять новые строки, удалять старые, менять слова местами —
   игра сама всё подхватит. Групп должно быть минимум две.

   Алгоритм: случайно выбираются две группы, слова каждой группы случайно
   делятся на два списка. Списки падают по очереди — по одному списку
   на строчку стихотворения.
   ========================================================================= */

